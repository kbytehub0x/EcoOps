"""Diff parser and dynamic child-pipeline generator.

Takes git diff or list of changed files, runs fail-safe validation,
selects the minimal safe test set, and generates the dynamic child-pipeline YAML.
"""

from typing import List, Dict, Any
from .fallback_rules import should_fallback_to_full_suite, SERVICE_TEST_MAP

FULL_TEST_SUITE = [
    "demo-app/tests/test_auth.py",
    "demo-app/tests/test_billing.py",
    "demo-app/tests/test_core.py",
]


def resolve_tests_for_changes(changed_files: List[str]) -> Dict[str, Any]:
    """Resolve which tests to run based on changed files and safety rules.
    
    Returns a dictionary with:
        - fallback_triggered: bool
        - reason: str
        - selected_tests: List[str]
        - total_tests_count: int
        - selected_tests_count: int
    """
    fallback_needed, reason = should_fallback_to_full_suite(changed_files)

    if fallback_needed:
        return {
            "fallback_triggered": True,
            "reason": reason,
            "selected_tests": FULL_TEST_SUITE,
            "total_available_test_files": len(FULL_TEST_SUITE),
            "selected_test_files_count": len(FULL_TEST_SUITE),
        }

    selected: set = set()
    for file_path in changed_files:
        norm_path = file_path.replace("\\", "/")
        for prefix, test_target in SERVICE_TEST_MAP.items():
            if prefix in norm_path:
                selected.add(test_target)

    selected_list = sorted(list(selected))

    # Defensive check: if mapping produced empty set somehow, fallback
    if not selected_list:
        return {
            "fallback_triggered": True,
            "reason": "Mapping resulted in 0 selected tests; falling back to full suite.",
            "selected_tests": FULL_TEST_SUITE,
            "total_available_test_files": len(FULL_TEST_SUITE),
            "selected_test_files_count": len(FULL_TEST_SUITE),
        }

    return {
        "fallback_triggered": False,
        "reason": reason,
        "selected_tests": selected_list,
        "total_available_test_files": len(FULL_TEST_SUITE),
        "selected_test_files_count": len(selected_list),
    }


def generate_child_pipeline_yaml(selected_tests: List[str], fallback_triggered: bool) -> str:
    """Generate dynamic child pipeline YAML content for GitLab CI.
    
    Uses standard GitLab child pipeline syntax:
        stages:
          - test
        test-job:
          stage: test
          script: ...
    """
    test_args = " ".join(selected_tests)
    pipeline_header = "# Auto-generated by EcoOps Dynamic Test Selector\n"
    if fallback_triggered:
        pipeline_header += "# MODE: Safety Fallback (Full Test Suite Executed)\n\n"
    else:
        pipeline_header += "# MODE: Carbon-Optimized Pruned Test Suite\n\n"

    yaml_content = f"""{pipeline_header}stages:
  - test

run-pruned-tests:
  stage: test
  image: python:3.11-slim
  rules:
    - when: always
  before_script:
    - pip install pytest
  script:
    - pytest {test_args} -v
  artifacts:
    reports:
      junit: junit-report.xml
    when: always
"""
    return yaml_content
